/**
 * 跨页面的展示阈值。
 *
 * 这些数原先散在各处:卡片高度占屏幕的比例在两个文件里各算了一遍(连注释措辞
 * 都一样),内容截断的阈值在审批卡和产物预览里各写了一遍。同一个语义有多个副本,
 * 想统一调一次得先找齐 —— 所以收到这里。
 *
 * 注意别把聊天输入框的 maxLength 也塞进来:那是"你能打多少字",和"显示要不要
 * 折叠"是两件事,数值恰好接近纯属巧合。
 */

/**
 * 长内容的字符上限。超过就折叠起来,让人主动展开。
 *
 * 阈值按"手机上滚很久也滚不完"来定,不是按传输成本 —— 这些内容本来就已经在内存里了。
 */
export const PREVIEW_CHARS = 8000;

/**
 * 卡片类内容的高度上限占屏幕的比例。
 *
 * 底下的按钮必须留在视口内:这些卡片是"必须做出选择才能继续"的,
 * 内容一长就把按钮顶出屏幕,会让人以为卡住了。剩下的靠卡片内部滚动解决。
 */
export const CARD_MAX_H_RATIO = 0.42;

/**
 * 能安全放进剪贴板的字符上限。
 *
 * ⚠️ 安卓的剪贴板 buffer 只有 4096 字符,超了会被**静默截断** —— 而截断比失败更糟:
 * 你拿到的是半截内容,还不知道少了什么。所以留出余量定在 3000;超过这个数的
 * 改走"存成电脑上的文件 + 复制路径"(见 ChatScreen 的 copyMessage)。
 */
export const CLIPBOARD_MAX_CHARS = 3000;
