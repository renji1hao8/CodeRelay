import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
let listener;
const context={addEventListener:(name,callback)=>{assert.equal(name,'message');listener=callback;},Date,Map};
vm.runInNewContext(fs.readFileSync(new URL('../src/desktop/codex-live.js',import.meta.url),'utf8'),context);
const emit=(method,params,hostId='local')=>listener({data:{type:'mcp-notification',hostId,method,params}});
const read=()=>context.__remoteccCodexLive.snapshot('T');
emit('item/agentMessage/delta',{threadId:'T',itemId:'missing',delta:'suffix'});assert.equal(read().items.length,0);
emit('turn/started',{threadId:'T'});assert.equal(read().busy,true);
emit('item/started',{threadId:'T',item:{type:'agentMessage',id:'A',text:''}});
emit('item/agentMessage/delta',{threadId:'T',itemId:'A',delta:'中文'});
emit('item/agentMessage/delta',{threadId:'T',itemId:'A',delta:'流式'});
assert.equal(read().items[0].text,'中文流式');const ts=read().items[0].ts;
emit('item/completed',{threadId:'T',item:{type:'agentMessage',id:'A',text:'中文流式完成'}});
assert.equal(read().items.length,1);assert.equal(read().items[0].text,'中文流式完成');assert.equal(read().items[0].ts,ts);
emit('item/started',{threadId:'T',item:{type:'agentMessage',id:'remote',text:'wrong host'}},'other');assert.equal(read().items.length,1);
emit('item/started',{threadId:'T',item:{type:'reasoning',id:'private',text:'private'}});assert.equal(read().items.length,1);
emit('turn/completed',{threadId:'T'});assert.equal(read().busy,false);
console.log('OK desktop deltas, stable completion identity, host isolation, partial attach and private-item exclusion');
